"""Compiles sprite.hlsl with fxc (shader model 4.0) and writes the bytecode into
source/D3D11Shaders.h, so D3D11Device needs no shader compiler at run time.

Run it after changing sprite.hlsl, on Windows with the Windows SDK installed:

    python tools/shaders/compile_d3d11.py [path to fxc.exe]
"""
import glob
import os
import subprocess
import sys
import tempfile

here = os.path.dirname(os.path.abspath(__file__))
source = os.path.join(here, 'sprite.hlsl')
target = os.path.join(here, '..', '..', 'source', 'D3D11Shaders.h')


def find_fxc():
    if len(sys.argv) > 1:
        return sys.argv[1]
    kits = os.path.join(os.environ.get('ProgramFiles(x86)', r'C:\Program Files (x86)'), 'Windows Kits', '10', 'bin')
    found = sorted(glob.glob(os.path.join(kits, '10.*', 'x64', 'fxc.exe')))
    if not found:
        sys.exit('fxc.exe not found; pass its path')
    return found[-1]


def compile_shader(fxc, profile, entry):
    with tempfile.TemporaryDirectory() as folder:
        output = os.path.join(folder, entry + '.cso')
        subprocess.run([fxc, '/nologo', '/T', profile, '/E', entry, '/O3', '/Fo', output, source], check=True)
        with open(output, 'rb') as handle:
            return handle.read()


def to_array(name, data):
    lines = []
    for start in range(0, len(data), 16):
        lines.append('\t\t' + ', '.join('0x%02x' % byte for byte in data[start:start + 16]) + ',')
    return '\tstatic constexpr std::uint8_t %s[] = {\n%s\n\t};' % (name, '\n'.join(lines))


fxc = find_fxc()
vertex = compile_shader(fxc, 'vs_4_0', 'vertexMain')
pixel = compile_shader(fxc, 'ps_4_0', 'pixelMain')
header = '''#pragma once

// Generated by tools/shaders/compile_d3d11.py from tools/shaders/sprite.hlsl
// (fxc, shader model 4.0). Do not edit; run the script again instead.

#include <cstdint>

namespace litefont {

/**
 * D3D11Shaders - The compiled sprite shaders D3D11Device draws with: the
 * vertex shader (vertexMain) and the pixel shader (pixelMain).
 */
struct D3D11Shaders {
%s

%s
};

}
''' % (to_array('vertex', vertex), to_array('pixel', pixel))
with open(target, 'w', encoding='utf-8', newline='\n') as handle:
    handle.write(header)
print('wrote', os.path.normpath(target), len(vertex), 'and', len(pixel), 'bytes')
